import ApplicationServices
import AppKit
import Carbon

@MainActor
struct PasteTarget {
    private static let webAreaRole = "AXWebArea"
    let processID: pid_t
    let application: AXUIElement
    let focusedElement: AXUIElement?
    let focusedWindow: AXUIElement?

    static func capture() -> PasteTarget? {
        guard let app = NSWorkspace.shared.frontmostApplication,
              app.processIdentifier != ProcessInfo.processInfo.processIdentifier else { return nil }
        let pid = app.processIdentifier
        let element = AXUIElementCreateApplication(pid)
        AXUIElementSetMessagingTimeout(element, 0.12)
        // Chromium enables native accessibility when an assistive client asks for the app role.
        _ = string(kAXRoleAttribute, in: element)
        var focus = attribute(kAXFocusedUIElementAttribute, in: element)
        if focus == nil || focus.map({ string(kAXRoleAttribute, in: $0) == webAreaRole }) == true {
            // Electron exposes this attribute for third-party assistive clients.
            let flag = "AXManualAccessibility" as CFString
            var settable = DarwinBoolean(false)
            if AXUIElementIsAttributeSettable(element, flag, &settable) == .success, settable.boolValue {
                AXUIElementSetAttributeValue(element, flag, kCFBooleanTrue)
                focus = attribute(kAXFocusedUIElementAttribute, in: element)
            }
        }
        return PasteTarget(
            processID: pid, application: element,
            focusedElement: focus,
            focusedWindow: attribute(kAXFocusedWindowAttribute, in: element)
        )
    }

    func validate() throws {
        guard AXIsProcessTrusted(), CGPreflightPostEventAccess() else {
            throw VoiceTypeError.message("辅助功能未授权。")
        }
        guard NSWorkspace.shared.frontmostApplication?.processIdentifier == processID else {
            throw VoiceTypeError.message("原应用已失去焦点。")
        }
        if let originalWindow = focusedWindow {
            guard let currentWindow = Self.attribute(kAXFocusedWindowAttribute, in: application),
                  CFEqual(originalWindow, currentWindow) else {
                throw VoiceTypeError.message("原窗口已失去焦点或已切换。")
            }
        }

        // Check current focus to protect password fields and non-text UI controls, while tolerating
        // DOM refreshes in web/Electron apps and custom text views (e.g. terminals).
        if let current = Self.attribute(kAXFocusedUIElementAttribute, in: application) {
            AXUIElementSetMessagingTimeout(current, 0.12)
            if Self.string(kAXSubroleAttribute, in: current) == kAXSecureTextFieldSubrole {
                throw VoiceTypeError.message("密码框需要手动粘贴。")
            }
            let nonTextRoles: Set<String> = [
                kAXButtonRole, kAXCheckBoxRole, kAXRadioButtonRole,
                kAXPopUpButtonRole, kAXMenuItemRole, kAXSliderRole
            ]
            if let role = Self.string(kAXRoleAttribute, in: current), nonTextRoles.contains(role) {
                throw VoiceTypeError.message("当前焦点不是输入框。")
            }
        } else if focusedElement == nil && focusedWindow == nil {
            throw VoiceTypeError.message("未能识别原输入框。")
        }

        guard NSWorkspace.shared.frontmostApplication?.processIdentifier == processID else {
            throw VoiceTypeError.message("原窗口已失去焦点。")
        }
    }

    private static func attribute(_ name: String, in element: AXUIElement) -> AXUIElement? {
        var value: CFTypeRef?
        guard AXUIElementCopyAttributeValue(element, name as CFString, &value) == .success,
              let value, CFGetTypeID(value) == AXUIElementGetTypeID() else { return nil }
        return (value as! AXUIElement)
    }

    private static func string(_ name: String, in element: AXUIElement) -> String? {
        var value: CFTypeRef?
        guard AXUIElementCopyAttributeValue(element, name as CFString, &value) == .success else { return nil }
        return value as? String
    }
}

@MainActor
final class TextInsertion {
    private struct ClipboardRepresentation {
        let type: NSPasteboard.PasteboardType
        let data: Data
    }

    private struct ClipboardSnapshot {
        let items: [[ClipboardRepresentation]]
        let insertedChangeCount: Int
    }

    private let clipboard: NSPasteboard
    private var pendingRestore: ClipboardSnapshot?
    private var restoreTask: Task<Void, Never>?

    init(clipboard: NSPasteboard = .general) {
        self.clipboard = clipboard
    }

    private static let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    private static let autoGeneratedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")

    func paste(_ text: String, into target: PasteTarget?) throws {
        guard let target else { throw VoiceTypeError.message("未找到原输入框。") }
        try target.validate()
        guard let source = CGEventSource(stateID: .privateState),
              let down = CGEvent(keyboardEventSource: source, virtualKey: CGKeyCode(kVK_ANSI_V), keyDown: true),
              let up = CGEvent(keyboardEventSource: source, virtualKey: CGKeyCode(kVK_ANSI_V), keyDown: false) else {
            throw VoiceTypeError.message("系统未能创建粘贴按键。")
        }
        down.flags = .maskCommand
        up.flags = .maskCommand

        restore()
        let count = clipboard.changeCount
        let original = (clipboard.pasteboardItems ?? []).map { item in
            item.types.compactMap { type -> ClipboardRepresentation? in
                guard type != Self.transientType, type != Self.autoGeneratedType else { return nil }
                return item.data(forType: type).map { ClipboardRepresentation(type: type, data: $0) }
            }
        }.filter { !$0.isEmpty }

        try target.validate()
        guard clipboard.changeCount == count else {
            throw VoiceTypeError.message("剪贴板刚刚被其他操作更新。")
        }
        clipboard.clearContents()
        let transientItem = NSPasteboardItem()
        transientItem.setString(text, forType: .string)
        // Standard markers tell clipboard managers (Raycast, Paste, Maccy, etc.) to ignore transient paste injections.
        transientItem.setData(Data(), forType: Self.transientType)
        transientItem.setData(Data(), forType: Self.autoGeneratedType)
        let didWrite = clipboard.writeObjects([transientItem])
        pendingRestore = ClipboardSnapshot(items: original, insertedChangeCount: clipboard.changeCount)
        guard didWrite else {
            restore()
            throw VoiceTypeError.message("无法写入剪贴板。")
        }
        down.postToPid(target.processID)
        up.postToPid(target.processID)

        // Web content may consume the clipboard asynchronously after receiving the shortcut.
        restoreTask = Task { [weak self] in
            try? await Task.sleep(for: .milliseconds(900))
            guard !Task.isCancelled else { return }
            self?.restore()
        }
    }

    func copy(_ text: String) -> Bool {
        restoreTask?.cancel()
        restoreTask = nil
        pendingRestore = nil
        clipboard.clearContents()
        return clipboard.setString(text, forType: .string)
    }

    func restore() {
        restoreTask?.cancel()
        restoreTask = nil
        guard let snapshot = pendingRestore else { return }
        pendingRestore = nil
        // Keep any newer clipboard contents placed there by the user or another app.
        guard clipboard.changeCount == snapshot.insertedChangeCount else { return }
        clipboard.clearContents()
        let items = snapshot.items.map { representations in
            let item = NSPasteboardItem()
            for representation in representations {
                item.setData(representation.data, forType: representation.type)
            }
            return item
        }
        if !items.isEmpty { clipboard.writeObjects(items) }
    }
}
